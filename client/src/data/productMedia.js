export function buildProductGallery(product) {
  const pack =
    packImages[product.slug] || '/products/sea-buckthorn-juice-pack.jpg';
  const gallery = (galleries[product.slug] || []).map(([src, alt]) => ({
    src,
    alt,
  }));
  if (!gallery.length)
    gallery.push({ src: pack, alt: `${product.name} product pack` });
  if (product.slug === 'sea-buckthorn-juice') {
    gallery.push(...juiceGallery.map(([src, alt]) => ({ src, alt })));
  } else {
    // Until product-specific gallery photography is supplied, repeat the packshot
    // so every detail page keeps the same five-image gallery layout.
    while (gallery.length < 5)
      gallery.push({ src: pack, alt: `${product.name} product pack` });
  }
  if (productVideos[product.slug]) {
    gallery.push({
      video: productVideos[product.slug],
      src: pack,
      alt: `${product.name} product video`,
    });
  }
  return gallery;
}
